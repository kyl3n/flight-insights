"""Generate tiny real-wire-format fixtures; none contain aircraft flight data.

DataFlash bytes are assembled independently using the published FMT structure.
TLOG frames are generated by pymavlink 2.4.49, including its packet checksums.
Run: .venv/bin/python fixtures/logs/generate_synthetic.py
"""
from pathlib import Path
import struct

from pymavlink.dialects.v20 import ardupilotmega as mavlink

ROOT = Path(__file__).parent
SCHEMAS = [
    (129, "UNIT", "QBZ", "TimeUS,Id,Label"),
    (130, "MULT", "QBd", "TimeUS,Id,Mult"),
    (131, "FMTU", "QBNN", "TimeUS,FmtType,UnitIds,MultIds"),
    (132, "PARM", "QNff", "TimeUS,Name,Value,Default"),
    (133, "BAT", "QBffcBB", "TimeUS,Inst,Volt,Curr,Temp,RemPct,SH"),
    (134, "ATT", "Qcccccc", "TimeUS,DesRoll,Roll,DesPitch,Pitch,DesYaw,Yaw"),
    (135, "MSG", "QZ", "TimeUS,Message"),
]
WIRE = {"Q": "Q", "B": "B", "Z": "64s", "N": "16s", "d": "d", "f": "f", "c": "h"}


def records():
    for key, label in (("s", "s"), ("v", "V"), ("A", "A"), ("d", "deg"), ("O", "degC")):
        yield "UNIT", [0, ord(key), label]
    for key, value in (("F", 1e-6), ("0", 1), ("B", .01)):
        yield "MULT", [0, ord(key), value]
    yield "FMTU", [0, 133, "s#vAO--", "F-00B--"]
    yield "FMTU", [0, 134, "sdddddd", "FBBBBBB"]
    yield "MSG", [0, "SYNTHETIC ONLY; format fixture, no aircraft validation"]
    yield "PARM", [0, "ATC_RAT_RLL_P", .1, .1]
    for second in range(1, 6):
        if second == 3:
            yield "PARM", [second * 1_000_000, "ATC_RAT_RLL_P", .12, .1]
        yield "BAT", [second * 1_000_000, 0, 24., 10., 2000, 80, 100]
        yield "ATT", [second * 1_000_000, 300, 100, 0, 0, 0, 0]
    yield "PARM", [1000, "ATC_RAT_RLL_P", .12, .1]
    yield "BAT", [1000, 0, 23., 0., 0, 255, 0]


def generate_dataflash():
    binary, text = bytearray(), []
    by_name = {name: (type_id, codes, columns) for type_id, name, codes, columns in SCHEMAS}
    for type_id, name, codes, columns in SCHEMAS:
        length = 3 + struct.calcsize("<" + "".join(WIRE[c] for c in codes))
        binary += b"\xa3\x95\x80" + struct.pack("<BB4s16s64s", type_id, length, name.encode(), codes.encode(), columns.encode())
        text.append(f"FMT, {type_id}, {length}, {name}, {codes}, {columns}")
    for name, values in records():
        type_id, codes, _ = by_name[name]
        wire_values = [v.encode() if isinstance(v, str) else v for v in values]
        binary += b"\xa3\x95" + bytes([type_id]) + struct.pack("<" + "".join(WIRE[c] for c in codes), *wire_values)
        # DataFlash text output already applies intrinsic c scaling.
        printed = [v * .01 if c == "c" else v for c, v in zip(codes, values)]
        text.append(name + ", " + ", ".join(str(v) for v in printed))
    (ROOT / "synthetic-flight.bin").write_bytes(binary)
    (ROOT / "synthetic-flight.log").write_text("\n".join(text) + "\n")


def generate_tlog():
    output = bytearray()
    sender = mavlink.MAVLink(None, srcSystem=1, srcComponent=1)
    receive_us = 1_760_000_000_000_000

    def add(message, *, system=1, v1=False):
        nonlocal receive_us
        sender.srcSystem = system
        packet = message.pack(sender, force_mavlink1=v1)
        sender.seq = (sender.seq + 1) % 256
        output.extend(struct.pack(">Q", receive_us) + packet)
        receive_us += 250_000

    add(mavlink.MAVLink_heartbeat_message(2, 3, 0, 0, 3, 3), v1=True)
    add(mavlink.MAVLink_param_value_message(b"ATC_RAT_RLL_P", .1, 9, 2, 0))
    for second in range(1, 5):
        add(mavlink.MAVLink_attitude_message(second * 1000, .1, .2, .3, 0., 0., 0.))
        add(mavlink.MAVLink_battery_status_message(0, 0, 0, 2500, [24000] + [65535] * 9, 1000, -1, -1, 80))
    add(mavlink.MAVLink_param_value_message(b"ATC_RAT_RLL_P", .12, 9, 2, 0))
    add(mavlink.MAVLink_heartbeat_message(2, 3, 0, 0, 3, 3), system=2)
    add(mavlink.MAVLink_param_value_message(b"ATC_RAT_RLL_P", .2, 9, 1, 0), system=2)
    add(mavlink.MAVLink_attitude_message(100, 0., 0., 0., 0., 0., 0.))
    add(mavlink.MAVLink_battery_status_message(0, 0, 0, 32767, [65535] * 10, -1, -1, -1, -1))
    (ROOT / "synthetic-flight.tlog").write_bytes(output)


if __name__ == "__main__":
    generate_dataflash()
    generate_tlog()
